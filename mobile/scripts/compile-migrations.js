const fs = require('fs');
const path = require('path');

const drizzleDir = path.resolve(__dirname, '../drizzle');
const migrationsTsFile = path.resolve(__dirname, '../src/database/migrations.ts');

if (!fs.existsSync(drizzleDir)) {
  console.error('❌ Drizzle folder not found at:', drizzleDir);
  process.exit(1);
}

const sqlFiles = fs.readdirSync(drizzleDir)
  .filter(file => file.endsWith('.sql'))
  .sort();

console.log(`🔍 Found ${sqlFiles.length} migration files.`);

const migrations = sqlFiles.map(file => {
  const filePath = path.join(drizzleDir, file);
  const sqlContent = fs.readFileSync(filePath, 'utf8');
  const name = path.basename(file, '.sql');
  return {
    name,
    sql: sqlContent
  };
});

const tsCode = `// This file is autogenerated by compile-migrations.js. Do not edit manually.
export const MIGRATIONS: Array<{ name: string; sql: string }> = ${JSON.stringify(migrations, null, 2)};
`;

fs.writeFileSync(migrationsTsFile, tsCode, 'utf8');
console.log(`✅ Compiled migrations written to: ${migrationsTsFile}`);
